import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:logging/logging.dart';

import '../errors/app_exception.dart';
import '../../firebase_options.dart';

final _log = Logger('Firebase');

/// Owns the Firebase clients and the Firestore path layout.
///
/// Every document lives under `users/{uid}/…`. That is deliberate: it makes the
/// security rule one condition — `request.auth.uid == uid` — applied by prefix
/// rather than restated per collection, so a new collection cannot be added
/// without inheriting it. It also makes a cross-user query structurally
/// impossible rather than merely denied, which is a stronger guarantee than the
/// `where userId == auth.uid` arrangement a flat layout would need.
class FirebaseService {
  const FirebaseService._();

  static bool _initialised = false;

  /// Must be awaited once, before `runApp`.
  ///
  /// Takes no configuration arguments: the project details come from
  /// `firebase_options.dart`, generated by `flutterfire configure`, and from
  /// `google-services.json` on Android.
  static Future<void> initialise() async {
    if (_initialised) return;

    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );

    // Offline persistence is the replacement for the hand-rolled cache the
    // Supabase build needed. Firestore keeps a local copy of everything it has
    // read and serves reads from it when the device is offline, so the dashboard
    // and transaction list work without a connection and writes queue rather
    // than failing.
    firestore.settings = const Settings(
      persistenceEnabled: true,
      cacheSizeBytes: Settings.CACHE_SIZE_UNLIMITED,
    );

    _initialised = true;
    _log.info('Firebase initialised');
  }

  static FirebaseFirestore get firestore => FirebaseFirestore.instance;
  static FirebaseAuth get auth => FirebaseAuth.instance;
  static User? get user => auth.currentUser;
  static String? get userId => auth.currentUser?.uid;
  static bool get isSignedIn => auth.currentUser != null;

  /// The signed-in user's id, or a thrown [AuthenticationException].
  ///
  /// Repositories call this rather than accepting a user id from the UI: an id
  /// supplied by the caller could be anyone's, while this one comes from the
  /// verified token. The security rules enforce the same thing server-side.
  static String requireUserId() {
    final id = auth.currentUser?.uid;
    if (id == null) {
      throw const AuthenticationException(
        'Your session has expired. Please sign in again.',
      );
    }
    return id;
  }

  // -------------------------------------------------------------------------
  // Paths
  // -------------------------------------------------------------------------
  // Collected here so a path appears once. A typo in a collection name is
  // otherwise a silent empty result rather than an error, because Firestore
  // creates collections on demand and reading a non-existent one returns zero
  // documents quite happily.

  static DocumentReference<Map<String, dynamic>> userDoc([String? uid]) =>
      firestore.collection(Paths.users).doc(uid ?? requireUserId());

  static CollectionReference<Map<String, dynamic>> _sub(
    String name, [
    String? uid,
  ]) =>
      userDoc(uid).collection(name);

  /// Preferences, kept in their own document rather than as fields on the user
  /// doc. The profile is read on nearly every screen; the settings are read once
  /// at startup, and a toggle should not invalidate the profile snapshot every
  /// listener is watching.
  static DocumentReference<Map<String, dynamic>> settingsDoc([String? uid]) =>
      _sub(Paths.settings, uid).doc(Paths.settingsDocId);

  static CollectionReference<Map<String, dynamic>> accounts([String? uid]) =>
      _sub(Paths.accounts, uid);

  static CollectionReference<Map<String, dynamic>> categories([String? uid]) =>
      _sub(Paths.categories, uid);

  static CollectionReference<Map<String, dynamic>> transactions([String? uid]) =>
      _sub(Paths.transactions, uid);

  static CollectionReference<Map<String, dynamic>> splits(
    String transactionId, [
    String? uid,
  ]) =>
      transactions(uid).doc(transactionId).collection(Paths.splits);

  static CollectionReference<Map<String, dynamic>> budgets([String? uid]) =>
      _sub(Paths.budgets, uid);

  static CollectionReference<Map<String, dynamic>> savingsGoals([String? uid]) =>
      _sub(Paths.savingsGoals, uid);

  static CollectionReference<Map<String, dynamic>> contributions(
    String goalId, [
    String? uid,
  ]) =>
      savingsGoals(uid).doc(goalId).collection(Paths.contributions);

  static CollectionReference<Map<String, dynamic>> lendings([String? uid]) =>
      _sub(Paths.lendings, uid);

  static CollectionReference<Map<String, dynamic>> bills([String? uid]) =>
      _sub(Paths.bills, uid);

  static CollectionReference<Map<String, dynamic>> subscriptions([
    String? uid,
  ]) =>
      _sub(Paths.subscriptions, uid);

  static CollectionReference<Map<String, dynamic>> recurring([String? uid]) =>
      _sub(Paths.recurring, uid);

  static CollectionReference<Map<String, dynamic>> documents([String? uid]) =>
      _sub(Paths.documents, uid);

  static CollectionReference<Map<String, dynamic>> ocrJobs([String? uid]) =>
      _sub(Paths.ocrJobs, uid);

  static CollectionReference<Map<String, dynamic>> ocrResults(
    String jobId, [
    String? uid,
  ]) =>
      ocrJobs(uid).doc(jobId).collection(Paths.ocrResults);

  static CollectionReference<Map<String, dynamic>> ocrCandidates([
    String? uid,
  ]) =>
      _sub(Paths.ocrCandidates, uid);

  static CollectionReference<Map<String, dynamic>> notifications([
    String? uid,
  ]) =>
      _sub(Paths.notifications, uid);

  /// Maintained monthly rollups.
  ///
  /// Firestore bills per document read, so summing a year of transactions to
  /// draw a chart would be both slow and expensive. A Cloud Function keeps one
  /// document per month per user up to date as transactions are written, and the
  /// dashboard reads those instead. Document id is `YYYY-MM`.
  static CollectionReference<Map<String, dynamic>> monthlySummaries([
    String? uid,
  ]) =>
      _sub(Paths.monthlySummaries, uid);

  static DocumentReference<Map<String, dynamic>> monthlySummary(
    DateTime month, [
    String? uid,
  ]) =>
      monthlySummaries(uid).doc(monthKey(month));

  /// `2026-09`. Used as the rollup document id, so it sorts chronologically.
  static String monthKey(DateTime date) =>
      '${date.year.toString().padLeft(4, '0')}-'
      '${date.month.toString().padLeft(2, '0')}';
}

/// Collection names, in one place.
class Paths {
  const Paths._();

  static const String users = 'users';
  static const String settings = 'settings';
  static const String settingsDocId = 'app';
  static const String accounts = 'accounts';
  static const String categories = 'categories';
  static const String transactions = 'transactions';
  static const String splits = 'splits';
  static const String budgets = 'budgets';
  static const String savingsGoals = 'savingsGoals';
  static const String contributions = 'contributions';
  static const String lendings = 'lendings';
  static const String bills = 'bills';
  static const String subscriptions = 'subscriptions';
  static const String recurring = 'recurringTransactions';
  static const String documents = 'documents';
  static const String ocrJobs = 'ocrJobs';
  static const String ocrResults = 'results';
  static const String ocrCandidates = 'ocrCandidates';
  static const String notifications = 'notifications';
  static const String monthlySummaries = 'monthlySummaries';

  /// Storage folders. One bucket with four prefixes, because Firebase charges
  /// per bucket beyond the first and a prefix rule isolates just as well.
  static const String storageDocuments = 'documents';
  static const String storageReceipts = 'receipts';
  static const String storageProfileImages = 'profile-images';
  static const String storageReports = 'reports';
}

/// Names of the callable Cloud Functions.
///
/// Anything that writes more than one document goes through one of these. A
/// client-side multi-write that lost connectivity halfway would leave a transfer
/// with one leg, or a split set that does not add up — Firestore has no deferred
/// constraint to catch it afterwards, so the write has to be server-side and
/// atomic.
class Callables {
  const Callables._();

  static const String createTransfer = 'createTransfer';
  static const String updateTransfer = 'updateTransfer';
  static const String deleteTransfer = 'deleteTransfer';
  static const String replaceSplits = 'replaceTransactionSplits';
  static const String confirmOcrCandidate = 'confirmOcrCandidate';
  static const String ignoreOcrCandidate = 'ignoreOcrCandidate';
  static const String cancelOcrJob = 'cancelOcrJob';
  static const String markBillPaid = 'markBillPaid';
  static const String contributeToGoal = 'contributeToGoal';
  static const String processDocument = 'processDocument';
  static const String findDuplicates = 'findDuplicates';
  static const String exportMyData = 'exportMyData';
  static const String deleteAccount = 'deleteAccount';
}
